# -*- coding: utf-8 -*-
"""
PyKuai Isolated Browser YouTube Sign-In Helper
Launches a user-installed Chromium browser in an isolated profile directory (~/.pykuai/yt-session),
lets the user sign in directly on official Google/YouTube pages, and saves Netscape cookies.txt
to ~/.pykuai/cookies.txt without installing extensions or reading personal browser profiles.
"""
from __future__ import annotations

import base64
import json
import os
import re
import shutil
import socket
import struct
import subprocess
import tempfile
import time
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path
from typing import Any, Optional

USER_CONFIG_DIR = Path.home() / ".pykuai"
DEFAULT_COOKIES_FILE = USER_CONFIG_DIR / "cookies.txt"
BROWSER_PROFILE_DIR = USER_CONFIG_DIR / "yt-session"
YOUTUBE_LOGIN_URL = (
    "https://accounts.google.com/ServiceLogin"
    "?service=youtube&continue=https%3A%2F%2Fwww.youtube.com%2F"
)

_AUTH_COOKIE_NAMES = frozenset(
    {
        "SID",
        "HSID",
        "SSID",
        "APISID",
        "SAPISID",
        "__Secure-1PAPISID",
        "__Secure-3PAPISID",
        "__Secure-1PSID",
        "__Secure-3PSID",
    }
)
_CORE_AUTH_NAMES = frozenset({"SID", "SAPISID", "__Secure-1PAPISID", "__Secure-3PAPISID"})
_GOOGLE_YT_DOMAIN_SUFFIXES = (
    "youtube.com",
    "google.com",
    "googlevideo.com",
    "youtu.be",
    "googleusercontent.com",
    "ggpht.com",
    "gstatic.com",
)


def _domain_matches(domain: str, suffixes: tuple[str, ...]) -> bool:
    clean = (domain or "").strip().lower().lstrip(".")
    return any(clean == sfx or clean.endswith(f".{sfx}") for sfx in suffixes)


def _is_youtube_home_url(url: str) -> bool:
    try:
        host = (urllib.parse.urlparse(url).hostname or "").lower()
    except ValueError:
        return False
    return host in {"www.youtube.com", "youtube.com", "m.youtube.com"}


def _auth_cookie_signature(cookies: list[dict[str, Any]]) -> dict[tuple[str, str], str]:
    sig: dict[tuple[str, str], str] = {}
    for cookie in cookies:
        domain = str(cookie.get("domain") or "").strip().lower()
        name = str(cookie.get("name") or "")
        value = str(cookie.get("value") or "")
        if _domain_matches(domain, ("youtube.com",)) and name in _AUTH_COOKIE_NAMES and value:
            sig[(domain, name)] = value
    return sig


def has_youtube_auth_cookies(cookies: list[dict[str, Any]]) -> bool:
    """Return True when cookies include authenticated YouTube session tokens."""
    sig = _auth_cookie_signature(cookies)
    present_names = {name for _, name in sig}
    return bool(present_names & _CORE_AUTH_NAMES)


def cookies_to_netscape(cookies: list[dict[str, Any]]) -> str:
    """Serialize Chromium/CDP cookie dicts into Netscape cookies.txt format for yt-dlp."""
    lines = [
        "# Netscape HTTP Cookie File",
        "# Generated by pykuai isolated YouTube sign-in",
        "",
    ]
    seen: set[tuple[str, str, str]] = set()
    for cookie in cookies:
        raw_domain = str(cookie.get("domain") or "").strip()
        if not raw_domain or not _domain_matches(raw_domain, _GOOGLE_YT_DOMAIN_SUFFIXES):
            continue
        name = str(cookie.get("name") or "").replace("\t", " ").replace("\r", "").replace("\n", "")
        if not name:
            continue
        path = str(cookie.get("path") or "/").replace("\t", " ").replace("\r", "").replace("\n", "")
        key = (raw_domain, path, name)
        if key in seen:
            continue
        seen.add(key)

        flag = "TRUE" if raw_domain.startswith(".") else "FALSE"
        secure = "TRUE" if cookie.get("secure") else "FALSE"
        raw_exp = cookie.get("expires", 0)
        try:
            exp_val = float(raw_exp) if raw_exp is not None else 0.0
        except (TypeError, ValueError):
            exp_val = 0.0
        expires = "0" if cookie.get("session") or exp_val <= 0 else str(int(exp_val))
        value = str(cookie.get("value") or "").replace("\t", " ").replace("\r", "").replace("\n", "")
        lines.append(f"{raw_domain}\t{flag}\t{path}\t{secure}\t{expires}\t{name}\t{value}")

    return "\n".join(lines) + "\n"


def write_cookies_file(cookies: list[dict[str, Any]], dest_path: Path) -> Path:
    """Write Netscape-formatted Google/YouTube cookies atomically to dest_path."""
    content = cookies_to_netscape(cookies)
    dest = Path(dest_path)
    dest.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp_name = tempfile.mkstemp(prefix=".cookies_", suffix=".tmp", dir=str(dest.parent))
    tmp_path = Path(tmp_name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(content)
        os.replace(tmp_path, dest)
        if os.name != "nt":
            try:
                os.chmod(dest, 0o600)
            except OSError:
                pass
    finally:
        if tmp_path.exists():
            try:
                tmp_path.unlink()
            except OSError:
                pass
    return dest


def find_chromium_browser() -> Optional[tuple[str, str]]:
    """Locate an installed Chrome, Edge, or Brave executable without modifying its profile."""
    if os.name == "nt":
        local_app = os.environ.get("LOCALAPPDATA", "")
        prog_files = os.environ.get("PROGRAMFILES", r"C:\Program Files")
        prog_x86 = os.environ.get("PROGRAMFILES(X86)", r"C:\Program Files (x86)")
        candidates = [
            (
                "Chrome",
                [
                    os.path.join(prog_files, "Google", "Chrome", "Application", "chrome.exe"),
                    os.path.join(prog_x86, "Google", "Chrome", "Application", "chrome.exe"),
                    os.path.join(local_app, "Google", "Chrome", "Application", "chrome.exe") if local_app else "",
                    shutil.which("chrome") or "",
                ],
            ),
            (
                "Microsoft Edge",
                [
                    os.path.join(prog_x86, "Microsoft", "Edge", "Application", "msedge.exe"),
                    os.path.join(prog_files, "Microsoft", "Edge", "Application", "msedge.exe"),
                    os.path.join(local_app, "Microsoft", "Edge", "Application", "msedge.exe") if local_app else "",
                    shutil.which("msedge") or "",
                ],
            ),
            (
                "Brave",
                [
                    os.path.join(prog_files, "BraveSoftware", "Brave-Browser", "Application", "brave.exe"),
                    os.path.join(local_app, "BraveSoftware", "Brave-Browser", "Application", "brave.exe")
                    if local_app
                    else "",
                    shutil.which("brave") or "",
                ],
            ),
        ]
    else:
        candidates = [
            (
                "Chrome",
                [
                    "/Applications/Google Chrome.app/Contents/MacOS/Google Chrome",
                    shutil.which("google-chrome") or "",
                    shutil.which("chromium") or "",
                    shutil.which("chromium-browser") or "",
                ],
            ),
            (
                "Microsoft Edge",
                [
                    "/Applications/Microsoft Edge.app/Contents/MacOS/Microsoft Edge",
                    shutil.which("microsoft-edge") or "",
                ],
            ),
            (
                "Brave",
                [
                    "/Applications/Brave Browser.app/Contents/MacOS/Brave Browser",
                    shutil.which("brave-browser") or "",
                ],
            ),
        ]

    for label, paths in candidates:
        for exe in paths:
            if exe and os.path.isfile(exe):
                return label, exe
    return None


def _pick_free_port() -> int:
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.bind(("127.0.0.1", 0))
        return int(sock.getsockname()[1])


def _fetch_cdp_version_ws(port: int, proc: subprocess.Popen[bytes], *, timeout: float = 12.0) -> str:
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
    deadline = time.monotonic() + timeout
    url = f"http://127.0.0.1:{port}/json/version"
    while time.monotonic() < deadline:
        if proc.poll() is not None:
            raise RuntimeError("Login browser exited before DevTools endpoint became ready.")
        try:
            with opener.open(url, timeout=1.0) as resp:
                data = json.loads(resp.read().decode("utf-8", errors="replace"))
            ws_url = str(data.get("webSocketDebuggerUrl") or "")
            if ws_url:
                return ws_url
        except (urllib.error.URLError, OSError, ValueError):
            time.sleep(0.15)
    raise RuntimeError("Timed out waiting for the isolated browser DevTools endpoint.")


class _CdpClient:
    """Minimal stdlib RFC 6455 WebSocket client for local Chrome DevTools Protocol."""

    def __init__(self, ws_url: str, *, timeout: float = 5.0) -> None:
        parsed = urllib.parse.urlparse(ws_url)
        if parsed.scheme != "ws" or not parsed.hostname or not parsed.port:
            raise ValueError(f"Unsupported CDP WebSocket URL: {ws_url}")
        self._sock = socket.create_connection((parsed.hostname, parsed.port), timeout=timeout)
        self._buf = b""
        self._next_id = 1
        path = parsed.path or "/"
        if parsed.query:
            path = f"{path}?{parsed.query}"
        self._handshake(f"{parsed.hostname}:{parsed.port}", path)

    def _handshake(self, host_hdr: str, path: str) -> None:
        key = base64.b64encode(os.urandom(16)).decode("ascii")
        req = (
            f"GET {path} HTTP/1.1\r\n"
            f"Host: {host_hdr}\r\n"
            "Upgrade: websocket\r\n"
            "Connection: Upgrade\r\n"
            f"Sec-WebSocket-Key: {key}\r\n"
            "Sec-WebSocket-Version: 13\r\n\r\n"
        )
        self._sock.sendall(req.encode("ascii"))
        while b"\r\n\r\n" not in self._buf:
            chunk = self._sock.recv(4096)
            if not chunk:
                raise EOFError("WebSocket handshake closed unexpectedly.")
            self._buf += chunk
        header_end = self._buf.index(b"\r\n\r\n") + 4
        headers, self._buf = self._buf[:header_end], self._buf[header_end:]
        status_line = headers.split(b"\r\n", 1)[0]
        if b"101" not in status_line:
            raise RuntimeError(f"CDP WebSocket upgrade failed: {status_line.decode('ascii', errors='replace')}")

    def _recv_exact(self, count: int) -> bytes:
        while len(self._buf) < count:
            chunk = self._sock.recv(65536)
            if not chunk:
                raise EOFError("CDP WebSocket connection closed.")
            self._buf += chunk
        out, self._buf = self._buf[:count], self._buf[count:]
        return out

    def _send_frame(self, opcode: int, payload: bytes) -> None:
        mask = os.urandom(4)
        header = bytearray([0x80 | (opcode & 0x0F)])
        length = len(payload)
        if length < 126:
            header.append(0x80 | length)
        elif length < 65536:
            header.append(0x80 | 126)
            header.extend(struct.pack("!H", length))
        else:
            header.append(0x80 | 127)
            header.extend(struct.pack("!Q", length))
        header.extend(mask)
        masked = bytes(b ^ mask[i % 4] for i, b in enumerate(payload))
        self._sock.sendall(bytes(header) + masked)

    def _recv_text_message(self) -> str:
        fragments: list[bytes] = []
        while True:
            b1, b2 = self._recv_exact(2)
            fin = (b1 & 0x80) != 0
            opcode = b1 & 0x0F
            length = b2 & 0x7F
            if length == 126:
                length = struct.unpack("!H", self._recv_exact(2))[0]
            elif length == 127:
                length = struct.unpack("!Q", self._recv_exact(8))[0]
            if b2 & 0x80:
                mask = self._recv_exact(4)
                raw = self._recv_exact(length)
                data = bytes(b ^ mask[i % 4] for i, b in enumerate(raw))
            else:
                data = self._recv_exact(length)

            if opcode == 0x8:
                raise EOFError("CDP WebSocket closed by browser.")
            if opcode == 0x9:
                self._send_frame(0xA, data)
                continue
            if opcode == 0xA:
                continue
            if opcode in (0x1, 0x0):
                fragments.append(data)
                if fin:
                    return b"".join(fragments).decode("utf-8", errors="replace")

    def call(self, method: str, params: Optional[dict[str, Any]] = None) -> dict[str, Any]:
        req_id = self._next_id
        self._next_id += 1
        payload = json.dumps({"id": req_id, "method": method, "params": params or {}}).encode("utf-8")
        self._send_frame(0x1, payload)
        while True:
            msg = json.loads(self._recv_text_message())
            if msg.get("id") != req_id:
                continue
            if "error" in msg:
                raise RuntimeError(f"CDP {method} failed: {msg['error']}")
            return dict(msg.get("result") or {})

    def close(self) -> None:
        try:
            self._sock.close()
        except OSError:
            pass

    def __enter__(self) -> "_CdpClient":
        return self

    def __exit__(self, *args: object) -> None:
        self.close()


def _terminate_browser(proc: subprocess.Popen[bytes], cdp: Optional[_CdpClient] = None) -> None:
    if cdp is not None:
        try:
            cdp.call("Browser.close")
            if proc.poll() is None:
                proc.wait(timeout=3)
        except Exception:
            pass
    if proc.poll() is None:
        try:
            proc.terminate()
            proc.wait(timeout=3)
        except Exception:
            try:
                proc.kill()
                proc.wait(timeout=2)
            except Exception:
                pass


def login_youtube_and_save_cookies(
    *,
    cookies_path: Optional[Path] = None,
    profile_dir: Optional[Path] = None,
    proxy_url: str = "",
    timeout_seconds: int = 300,
    poll_interval: float = 1.0,
    console=None,
) -> Optional[Path]:
    """Open an isolated browser for official Google/YouTube login and save Netscape cookies.txt."""
    def _emit(msg: str) -> None:
        if console is not None:
            console.print(msg)
        else:
            print(re.sub(r"\[/?[^\]]+\]", "", msg))

    browser = find_chromium_browser()
    if not browser:
        _emit(
            "[bold #FF5252]✗ No Chrome, Microsoft Edge, or Brave installation found.[/bold #FF5252]\n"
            "[dim]Install Edge/Chrome/Firefox or place Netscape cookies.txt in ~/.pykuai/cookies.txt[/dim]"
        )
        return None

    browser_name, browser_exe = browser
    dest = Path(cookies_path) if cookies_path is not None else DEFAULT_COOKIES_FILE
    session_dir = Path(profile_dir) if profile_dir is not None else BROWSER_PROFILE_DIR
    dest.parent.mkdir(parents=True, exist_ok=True)
    session_dir.mkdir(parents=True, exist_ok=True)

    port = _pick_free_port()
    cmd = [
        browser_exe,
        f"--user-data-dir={session_dir}",
        f"--remote-debugging-port={port}",
        "--remote-debugging-address=127.0.0.1",
        "--no-first-run",
        "--no-default-browser-check",
        "--disable-sync",
        "--window-size=980,760",
        "--new-window",
    ]
    clean_proxy = (proxy_url or "").strip()
    if clean_proxy:
        cmd.append(f"--proxy-server={clean_proxy}")
    cmd.append(YOUTUBE_LOGIN_URL)

    _emit(f"[#00FF00]› Opening isolated {browser_name} session (~/.pykuai/yt-session)...[/#00FF00]")
    _emit(
        "[dim]Sign in to your Google / YouTube account in the browser window.\n"
        "Cookies will save automatically to ~/.pykuai/cookies.txt once signed in "
        "(or close the browser window when done; Ctrl+C cancels).[/dim]"
    )

    try:
        proc = subprocess.Popen(cmd, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    except OSError as exc:
        _emit(f"[bold #FF5252]✗ Unable to launch {browser_name}: {exc}[/bold #FF5252]")
        return None

    latest_cookies: list[dict[str, Any]] = []
    dest_existed_before = dest.is_file()
    cdp: Optional[_CdpClient] = None
    try:
        ws_url = _fetch_cdp_version_ws(port, proc)
        cdp = _CdpClient(ws_url, timeout=5.0)

        initial_cookies = list(cdp.call("Storage.getCookies").get("cookies") or [])
        latest_cookies = initial_cookies
        initial_sig = _auth_cookie_signature(initial_cookies)

        deadline = time.monotonic() + timeout_seconds
        while time.monotonic() < deadline:
            if proc.poll() is not None:
                break
            try:
                cookies = list(cdp.call("Storage.getCookies").get("cookies") or [])
                latest_cookies = cookies
                targets = list(cdp.call("Target.getTargets").get("targetInfos") or [])
            except (EOFError, OSError, RuntimeError):
                break

            cur_sig = _auth_cookie_signature(cookies)
            on_youtube = any(
                _is_youtube_home_url(str(t.get("url") or ""))
                for t in targets
                if t.get("type") == "page"
            )
            has_core_auth = has_youtube_auth_cookies(cookies)
            auth_changed = cur_sig != initial_sig or not dest_existed_before

            if has_core_auth and on_youtube and auth_changed:
                time.sleep(min(1.5, max(0.0, deadline - time.monotonic())))
                try:
                    latest_cookies = list(cdp.call("Storage.getCookies").get("cookies") or latest_cookies)
                except (EOFError, OSError, RuntimeError):
                    pass
                saved = write_cookies_file(latest_cookies, dest)
                _terminate_browser(proc, cdp)
                _emit(f"[#00FF00]✓ Saved YouTube cookies to {saved}[/#00FF00]")
                return saved

            time.sleep(poll_interval)
        else:
            _emit("[yellow]⚠ Timed out waiting for YouTube sign-in.[/yellow]")
            _terminate_browser(proc, cdp)
            return None
    except KeyboardInterrupt:
        _emit("\n[dim]› YouTube login cancelled.[/dim]")
        _terminate_browser(proc, cdp)
        return None
    except Exception as exc:
        _emit(f"[bold #FF5252]✗ Browser login helper error: {exc}[/bold #FF5252]")
        _terminate_browser(proc, cdp)
        return None
    finally:
        if cdp is not None:
            cdp.close()

    # Handle manual browser close after signing in (or account refresh).
    if has_youtube_auth_cookies(latest_cookies):
        saved = write_cookies_file(latest_cookies, dest)
        _emit(f"[#00FF00]✓ Saved YouTube cookies to {saved}[/#00FF00]")
        return saved

    _emit("[yellow]⚠ Browser window closed before YouTube sign-in completed.[/yellow]")
    return None
